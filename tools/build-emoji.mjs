// build-emoji.mjs — vendor the Unicode emoji list, with names, for the picker.
//
// The space picker used to offer a hand-picked handful, which is fine until the
// one you want isn't there. The full set needs names to be searchable, and the
// authoritative source for both is Unicode's own emoji-test.txt.
//
// Same contract as tools/update-defuddle.mjs: run by hand, vendors a file, and
// the extension itself never makes this request. This one fetches DATA, not
// code — nothing here is executed, it is a table of characters and labels.
//
//   node tools/build-emoji.mjs           # report what would change
//   node tools/build-emoji.mjs --apply   # write vendor/emoji.js

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const OUT = path.join(ROOT, 'vendor', 'emoji.js');
// unicode.org serves 403 to scripted clients; the same file, from the Unicode
// Consortium's own repository, does not.
const SRC = 'https://raw.githubusercontent.com/unicode-org/unicodetools/main/' +
  'unicodetools/data/emoji/16.0/emoji-test.txt';

// Skin-tone and hair variants multiply the list ~5x for no browsing benefit;
// the base emoji is what a space wants as its badge.
// Multi-person emoji list each participant's tone after a COMMA, not a colon
// — "kiss: person, person, light skin tone, medium skin tone" — so matching on
// ": " alone left 350 of them behind.
const SKIP = /[,:] (light|medium-light|medium|medium-dark|dark) skin tone|[,:] (red|curly|white|bald) hair/;

const res = await fetch(SRC);
if (!res.ok) throw new Error(`${SRC} → ${res.status}`);
const text = await res.text();

let group = '';
const out = [];
const seen = new Set();
for (const line of text.split('\n')) {
  if (line.startsWith('# group:')) { group = line.slice(8).trim(); continue; }
  if (!line || line.startsWith('#')) continue;
  // 1F600 ; fully-qualified # 😀 E1.0 grinning face
  const m = /^([0-9A-F ]+);\s*fully-qualified\s*#\s*(\S+)\s+E[\d.]+\s+(.+)$/.exec(line.trim());
  if (!m) continue;
  const [, , char, name] = m;
  if (SKIP.test(name)) continue;
  if (seen.has(char)) continue;
  seen.add(char);
  out.push({ c: char, n: name.trim(), g: group });
}

const groups = [...new Set(out.map((e) => e.g))];
const body =
  '// Generated by tools/build-emoji.mjs from ' + SRC + '\n' +
  '// Data, not code: a table of characters and their Unicode names.\n' +
  `// ${out.length} emoji in ${groups.length} groups. Do not edit by hand.\n\n` +
  `export const EMOJI_GROUPS = ${JSON.stringify(groups)};\n\n` +
  'export const EMOJI = ' + JSON.stringify(out.map((e) => [e.c, e.n, groups.indexOf(e.g)])) + ';\n';

console.log(`${out.length} emoji, ${groups.length} groups, ${(body.length / 1024).toFixed(0)} KB`);
if (process.argv.includes('--apply')) {
  fs.writeFileSync(OUT, body);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
} else {
  console.log('(dry run — pass --apply to write)');
}
